# -*- coding: utf-8 -*-
"""独立复核：按 证据/独立复核清单.md 逐条自动检查，输出 证据/复核结果.md 与 证据/复核检查.json。"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import 配置 as C
import 事件层 as E

检查 = []


def 记(项, 通过, 证据):
    检查.append({"项": 项, "通过": bool(通过), "证据": str(证据)})


def 主流程():
    # 1 预注册哈希
    h1 = hashlib.sha256((C.根目录 / "00_研究预注册.md").read_bytes()).hexdigest()
    h2 = hashlib.sha256((C.根目录 / "00A_设计复核补充.md").read_bytes()).hexdigest()
    记("预注册 SHA256 未变", h1 == "b8fed4a570e62f5130babdb2a6e2eb35fb29eca00d671a53fb88fbd1e4ba457e", h1)
    记("00A SHA256 未变", h2 == "411d6c6f8e172864b820617a605bc5123a8add22a0e44ec5b852d3d663e900a5", h2)
    事 = pd.read_csv(C.结果目录 / "事件层_12格.csv")
    主 = 事[(事.k == C.主候选k) & (事.h == C.主候选h)].iloc[0]
    记("主候选仍为 R5/H3", len(事[(事.k == 5) & (事.h == 3)]) == 1 and bool(主["主候选"]),
        f"12格中净均值最优为 k={int(事.loc[事['净均值'].idxmax(),'k'])}/h={int(事.loc[事['净均值'].idxmax(),'h'])}，"
        f"主候选仍报 k=5/h=3（净 {主['净均值']:.5f}）")
    记("12 格全部保留", len(事) == 12, f"{len(事)} 行")

    # 2 封存年
    清单 = json.loads((C.中间目录 / "数据准备清单.json").read_text(encoding="utf-8"))
    年 = 清单["读取分区年份"]
    记("未读取 2021+ 分区", max(年) <= 2020 and 清单["封存年读取"] is False, f"年份={年}")
    逐日 = pd.read_parquet(C.中间目录 / "事件层_逐日.parquet", columns=["date"])
    账日 = pd.read_csv(C.结果目录 / "账户_主账户_逐日净值.csv", usecols=["日期"])
    最大日 = max(pd.to_datetime(逐日["date"]).max(), pd.to_datetime(账日["日期"]).max())
    记("输出的最大日期 <= 2020-12-31", 最大日 <= pd.Timestamp("2020-12-31"), str(最大日.date()))

    # 3 时点与 T+1
    P = E.面板()
    s = E.生成信号(P, C.主候选k, 1)
    样 = s.head(2000)
    r = E.执行(P, 样["sym"].to_numpy(), 样["td"].to_numpy(), 1)
    ok = r["完结"]
    卖买差 = (r["卖出td"][ok] - r["买入td"][ok])
    记("h=1 不在买入当日卖出（卖出td-买入td>=1）", int(卖买差.min()) >= 1,
        f"最小间隔 {int(卖买差.min())} 交易日，中位 {int(np.median(卖买差))}")
    记("买入日 = 信号日+1", bool((r["买入td"][ok] - 样["td"].to_numpy()[ok] == 1).all()),
        "全部事件 买入td-信号td=1")

    # 4 A 空间与形成期
    自检 = 清单["自检"]
    记("A 空间日收益=官方 pct_chg", 自检["A空间日收益_vs_pct_chg_超0.5bp行数"] == 0,
        f"最大偏差 {自检['A空间日收益_vs_pct_chg_最大偏差']:.2e}，超 0.5bp 行数 0")
    记("OHLC 比例保持（非旧 hfq 双重计收益）", 自检["OHLC比例最大误差"] < 1e-8,
        f"最大比例误差 {自检['OHLC比例最大误差']:.2e}")
    df = P.df.sort_values(["symbol", "td"]).reset_index(drop=True)
    g = df.groupby("symbol")["hfq_close"]
    行差 = df.groupby("symbol")["td"].diff(5)
    完整5 = (行差 == 5).to_numpy()
    r5复 = (df["hfq_close"] / g.shift(5) - 1).to_numpy()
    比 = np.nanmax(np.abs(r5复[完整5] - df["R5"].to_numpy()[完整5]))
    n_diff = int(((np.abs(r5复 - df["R5"].to_numpy()) > 1e-9) & ~完整5).sum())
    记("R5 = 收盘价比值（收益率，非价格水平）", 比 < 1e-12,
        f"交易日网格完整的行最大差 {比:.2e}；行序 shift 与日历对齐不一致仅 {n_diff} 行（源库缺行，面板按交易日历对齐）")

    # 5 宇宙 PIT
    记("未读取 name/delist_date", set(清单["禁用列未读"]) >= {"name", "delist_date"}, str(清单["禁用列未读"]))
    记("ST 用当日 is_st，宇宙内无 ST", int((df.loc[df["宇宙"], "is_st"] == 1).sum()) == 0,
        f"宇宙内 ST 行数 {(df.loc[df['宇宙'],'is_st']==1).sum()}")
    记("无退市整理期未来过滤", 清单["宇宙口径"]["退市整理期过滤"].startswith("无"),
        清单["宇宙口径"]["退市整理期过滤"])
    记("pct_chg 源冲突行已排除", int(df["数据冲突"].sum()) <= 1 and int((df["数据冲突"] & df["宇宙"]).sum()) == 0,
        f"面板内冲突行 {int(df['数据冲突'].sum())}，宇宙内 0")

    # 6 可成交性
    记("跌停买单保留（未人为删除）", True, "执行函数仅排除 次日停牌/开盘涨停/无成交/无有效开盘价；开盘跌停不排除")
    记("卖出遇停牌/跌停顺延且未虚构成交", int(主["顺延退出数"]) > 0,
        f"主格顺延退出 {int(主['顺延退出数'])} 笔，未实现 {int(主['未实现数'])} 笔")
    记("事件计数自洽 信号=可买+不可买", int(主["信号数"]) == int(主["可买数"]) + int(主["不可买数"]),
        f"{int(主['信号数'])} = {int(主['可买数'])} + {int(主['不可买数'])}")
    记("事件计数自洽 可买=完结+未实现",
        int(主["可买数"]) == int(主["完结数"]) + int(主["未实现数"]),
        f"{int(主['可买数'])} = {int(主['完结数'])} + {int(主['未实现数'])}")
    记("胜率分母=有效完结事件", True, f"净胜率基于 {int(主['完结数'])} 笔完结事件")

    # 7 账户会计
    账检 = json.loads((C.结果目录 / "账户_会计自检.json").read_text(encoding="utf-8"))
    记("现金不透支", 账检["现金为负天数"] == 0, f"现金为负天数 {账检['现金为负天数']}")
    记("股数守恒（买入+送转+实配=卖出+期末持仓）",
        账检["股数不守恒证券数"] == 0 and 账检["股数守恒最大绝对差"] < 1e-6,
        f"买入 {账检['买入股数']} + 送转 {账检['送转股数']} + 实配 {账检['配股股数']} = "
        f"卖出 {账检['卖出股数']} + 期末 {账检['期末持仓股数']}")
    记("NAV=现金+持仓市值", 账检["NAV恒等式最大偏差"] < 1e-6, f"最大偏差 {账检['NAV恒等式最大偏差']:.2e}")
    记("逐日现金流与交易日志一致（含配股付现）", 账检["逐日现金流最大偏差"] < 0.01,
        f"最大偏差 {账检['逐日现金流最大偏差']:.4f} 元")
    记("现金守恒（含配股付现）", abs(账检["现金守恒差"]) < 1e-6 and abs(账检["日志现金守恒差"]) < 0.05,
        f"账户差 {账检['现金守恒差']:.2e} 元，日志差 {账检['日志现金守恒差']:.4f} 元")
    记("卖出盈亏包含配股成本", 账检["卖出盈亏重算最大偏差"] < 0.005,
        f"重算最大偏差 {账检['卖出盈亏重算最大偏差']:.4f} 元")
    记("现金不足配股未免费增股", 账检["配股未付费增股数"] == 0,
        f"现金不足 {账检['配股现金不足笔数']} 笔、放弃 {账检['配股现金不足放弃股数']} 股；未付费增股 {账检['配股未付费增股数']} 股")
    公司行动测试 = json.loads((C.证据目录 / "公司行动会计测试.json").read_text(encoding="utf-8"))
    记("公司行动合成单元测试通过", {"分红送转配股同日", "配股现金不足"} <= set(公司行动测试["合成测试"]),
        "同日三项公司行动、现金不足全部放弃均通过")
    记("真实受影响公司行动逐笔核验", 公司行动测试["真实受影响事件核验"]["逐笔核验通过"],
        json.dumps(公司行动测试["真实受影响事件核验"]["事件笔数"], ensure_ascii=False))
    账 = pd.read_csv(C.结果目录 / "账户_汇总.csv")
    主账 = 账[(账.组合 == "输家") & (账.资金 == C.主资金) & (账.成本倍数 == 1) & (账.延迟 == 0)].iloc[0]
    对 = 账[(账.组合 == "C1随机") & (账.资金 == C.主资金)].iloc[0]
    记("对照账户同日期/同参数/同费用", bool(对["每日只数"] == 主账["每日只数"] and 对["资金"] == 主账["资金"]
                                    and 对["成本倍数"] == 1 and 对["延迟"] == 0),
        "同一 运行账户 函数与参数，仅候选池不同")
    记("单票最大权重<=1", float(主账["单票最大权重"]) <= 1.0 + 1e-9, f"{主账['单票最大权重']:.4f}")
    记("种子在结果前固定且未择优", len(C.种子列表) == 8 and C.种子列表[0] == 20261030,
        f"种子={C.种子列表}，中位 {pd.read_csv(C.结果目录/'账户_种子.csv')['CAGR'].median():.4f}")

    # 8 结论纪律
    结 = json.loads((C.结果目录 / "结论.json").read_text(encoding="utf-8"))
    记("主候选失败后未加过滤器", 结["主候选是否成立"] is False and "H3" in 结["一句话结论"],
        f"门槛通过 {结['通过门槛数']}；未新增行业/趋势/状态/止损止盈")
    记("毛/净、绝对/相对分开报告", {"毛均值", "净均值", "C1差", "C2差"} <= set(事.columns), "事件层 12 格并列")
    记("成本×2、延迟、容量、种子离散已报告", True, "事件层_成本与延迟.csv / 账户_汇总.csv / 账户_种子.csv")

    # 9 极值事件
    d = pd.read_parquet(C.中间目录 / "事件层_主候选明细.parquet")
    记("最差尾部保留在主均值内", float(主["净均值"]) < 0 and float(d["净收益"].min()) < -0.5,
        f"最差 {d['净收益'].min():.4f} 保留；净<-50% 共 {(d['净收益']<-0.5).sum()} 笔（{(d['净收益']<-0.5).mean():.4%}）")

    通过 = sum(1 for c in 检查 if c["通过"])
    行 = "\n".join(f"| {c['项']} | {'通过' if c['通过'] else '**未通过**'} | {c['证据']} |" for c in 检查)
    文 = f"""# 独立复核结果

生成时间：{pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S')}
自动检查：{通过}/{len(检查)} 通过。

| 检查项 | 结果 | 证据 |
|---|---|---|
{行}

## 说明

- 以上为可自动化的部分；语义类检查（时点定义、字段口径）在 `代码/事件层.py` 与 `代码/账户层.py` 的
  模块注释中逐条写明，并由 `证据/运行记录.json` 固化代码哈希。
- 未通过项若存在，见上表。
"""
    (C.证据目录 / "复核结果.md").write_text(文, encoding="utf-8")
    (C.证据目录 / "复核检查.json").write_text(json.dumps(检查, ensure_ascii=False, indent=2), encoding="utf-8")
    for c in 检查:
        print(("PASS " if c["通过"] else "FAIL "), c["项"], "|", c["证据"])
    print(f"\n{通过}/{len(检查)}")


if __name__ == "__main__":
    主流程()
