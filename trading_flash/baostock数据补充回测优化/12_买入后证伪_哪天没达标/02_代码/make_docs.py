CAND_ORDER = ["1-2", "3-9", "10-19", "20-49", "50-99", "100+"]
STATE_ORDER = ["上涨", "中震荡", "下跌"]


def cb(b, period="全期", col="最终亏损率"):
    r = CB[(CB["期间"] == period) & (CB["候选级别"] == b)]
    return r[col].iloc[0] if len(r) else np.nan


def cw(b, d=5, rule="收益<-2%", period="全期", col="最终亏损率"):
    r = CW[(CW["期间"] == period) & (CW["天数"] == d) & (CW["规则"] == rule) & (CW["候选级别"] == b)]
    return r[col].iloc[0] if len(r) else np.nan


def pct(x, d=1):
    return "—" if pd.isna(x) else f"{x*100:.{d}f}%"


def ci(lo, hi, d=1):
    if pd.isna(lo) or pd.isna(hi):
        return "—"
    return f"{lo*100:.{d}f}–{hi*100:.{d}f}%"


def n(x):
    return "—" if pd.isna(x) else f"{int(x):,}"


def co(d, rule, period="全期", sample="全部信号前二"):
    r = CO[(CO["样本"] == sample) & (CO["期间"] == period) &
           (CO["天数"] == d) & (CO["规则"] == rule)]
    return r.iloc[0] if len(r) else None


def th(d, thr, period="全期"):
    r = TH[(TH["样本"] == "全部信号前二") & (TH["期间"] == period) &
           (TH["天数"] == d) & np.isclose(TH["阈值"], thr)]
    return r.iloc[0] if len(r) else None


def fe(d, rule, period="全期"):
    r = FE[(FE["样本"] == "全部信号前二") & (FE["期间"] == period) &
           (FE["天数"] == d) & (FE["规则"] == rule)]
    return r.iloc[0] if len(r) else None


def sc(d, score, period="全期"):
    r = SC[(SC["样本"] == "全部信号前二") & (SC["期间"] == period) &
           (SC["天数"] == d) & (SC["预警分"] == score)]
    return r.iloc[0] if len(r) else None


def ea(d, rule, period="全期", sample="全部信号前二"):
    r = EA[(EA["样本"] == sample) & (EA["期间"] == period) &
           (EA["天数"] == d) & (EA["规则"] == rule)]
    return r.iloc[0] if len(r) else None


def sb(st, period="全期", sample="全部信号前二", col="最终亏损率"):
    r = SB[(SB["样本"] == sample) & (SB["期间"] == period) & (SB["状态"] == st)]
    return r[col].iloc[0] if len(r) else np.nan


def sw(st, rule, period="全期", sample="全部信号前二", col="最终亏损率"):
    r = SW[(SW["样本"] == sample) & (SW["期间"] == period) &
           (SW["状态"] == st) & (SW["规则"] == rule)]
    return r[col].iloc[0] if len(r) else np.nan


def sm(rg, st="全部", period="全期", col="最终亏损率"):
    r = SM[(SM["期间"] == period) & (SM["市场环境"] == rg) & (SM["状态"] == st)]
    return r[col].iloc[0] if len(r) else np.nan


def sth(kind, value, st, col="最终亏损率"):
    r = STH[(STH["敏感性"] == kind) & np.isclose(STH[kind], value) & (STH["状态"] == st)]
    return r[col].iloc[0] if len(r) else np.nan


DECISION = """## 怎么用

1. **D+3 收盘做第一次证伪。** 收盘 < -2% 记为“未通过”；若同时未创新高、跌破买入日最低、低于5日线，预警分≥4。此时不要追加，也不要把“跌了”解释成“更便宜了”。
2. **D+5 收盘做确认。** 仍 < -2% 时，最终亏损概率约 2/3；三项复合约 71%，最终≤-10% 约 42%。如果仓位或回撤预算紧张，这时应降仓，而不是等 D+10。
3. **如果目标是尾部保险，用更早、更宽的“没涨到 +3%”规则，或直接设硬止损。** 它把 ≤-15% 的深尾从约 11% 压到约 3%，代价是平均少赚约 4pp；这是保险，不是 alpha。
4. **先看 D+3 三态，再谈证伪。** 上涨组（≥+3%）只有回吐到成本/回撤≥10%才明显转弱；中震荡组（-2%~+3%）要等 D+5 < -2%；下跌组（≤-2%）在 D+3 已经是失败，D+5 只是确认。三态是事后分层，不是入场信号。
5. **不要把它当次日择时。** 触发后次日下跌概率 40–45%，并不高于基准；短期反而容易反弹。
6. **不要因为 D+5 触发就机械清仓。** 触发后持有到最终的均值仍高于 D+6 开盘早退 2–5pp；策略的 edge 本来就是“急跌后的反弹”。
"""

LIMITS = """## 限制

- **不是 1,256 个独立机会。** 按信号段聚类只有 925 段；同一股票连续信号高度重叠。置信区间按信号段聚类稳健标准误，仍不能消除重叠。
- **实际成交样本小。** 2017-2026 只有 107 笔，D+5 触发组 28 笔；95%CI 很宽。点估计只作方向参考。
- **口径混合。** 全部信号前二用模拟规则（+20% 止盈/15日）；实际成交 219 笔用逐笔净收益（含跳空止盈、跌停顺延、退市）。两者在基准上差 0.2–1.3pp。
- **早退是近似。** 按 d+1 开盘成交，不建模跌停卖不出、排队和滑点扩大；实际成交口径扣 0.2% 卖出费用，全部信号口径为毛收益。
- **只用了日线 OHLC。** 没有盘中路径、封单、盘口；+20% 止盈按盘中触价近似。
- **多重检验。** 本文看了约 20 条规则 × 5 个检查点，只保留两期方向一致、样本量足够的几条；没有做 Bonferroni/FDR 校正，仍存在数据挖掘风险。
- **三态是事后分层。** D+3 三态用 D+3 收盘分组，不是提前预测；上涨组 D+5 回吐规则只有 40/43 笔，实际成交 2017-26 只有 4 笔触发且 0 亏损，方向没有验证。市场环境分层也是描述性，且 2017-26 的“上涨市/下跌市”基线排序已经翻转。
- **描述性统计，不是因果。** “触发后亏损率更高”不等于“触发导致亏损”；它主要是“已经弱”的同义词。历史不代表未来，不构成投资建议。
"""


